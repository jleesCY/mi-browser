// The site's colours, made the way the app makes its own: a Material 3 scheme from one seed colour, in the Vibrant
// style (the app's materialkolor PaletteStyle.Vibrant), light and dark. Writes src/app/theme.css: every colour role as a
// CSS variable ("R G B", so Tailwind's opacity modifiers work), light by default and dark when the visitor's system is.
// Tailwind maps the roles to classes (tailwind.config.ts: bg-surface, text-on-surface, bg-primary-container…).
//
// Another mi. app's site: copy this site and change SEED to that app's default accent. Runs before dev and build.
import { writeFileSync } from "node:fs";
import { Hct, MaterialDynamicColors as C, SchemeVibrant, argbFromHex, hexFromArgb } from "@material/material-color-utilities";

/** mi. Browser's default accent (Settings › Look & Feel › Accent Color: Blue). */
const SEED = "#3D9BFF";

const ROLES = [
  "primary", "onPrimary", "primaryContainer", "onPrimaryContainer",
  "secondary", "onSecondary", "secondaryContainer", "onSecondaryContainer",
  "tertiary", "onTertiary", "tertiaryContainer", "onTertiaryContainer",
  "error", "onError", "errorContainer", "onErrorContainer",
  "surface", "onSurface", "surfaceVariant", "onSurfaceVariant", "surfaceDim", "surfaceBright",
  "surfaceContainerLowest", "surfaceContainerLow", "surfaceContainer", "surfaceContainerHigh", "surfaceContainerHighest",
  "outline", "outlineVariant", "inverseSurface", "inverseOnSurface", "inversePrimary",
];

const kebab = (s) => s.replace(/[A-Z]/g, (c) => "-" + c.toLowerCase());
const rgb = (argb) => `${(argb >> 16) & 255} ${(argb >> 8) & 255} ${argb & 255}`;
const schemeOf = (dark) => new SchemeVibrant(Hct.fromInt(argbFromHex(SEED)), dark, 0);
const vars = (dark) => {
  const scheme = schemeOf(dark);
  return ROLES.map((r) => `  --md-${kebab(r)}: ${rgb(C[r].getArgb(scheme))};`).join("\n");
};

writeFileSync(new URL("../src/app/theme.css", import.meta.url), `/* Generated by scripts/theme.mjs from the seed ${SEED} (Material 3, Vibrant). Don't edit: change the seed. */
:root {
  color-scheme: light;
${vars(false)}
}

@media (prefers-color-scheme: dark) {
  :root {
    color-scheme: dark;
${vars(true).replace(/^/gm, "  ")}
  }
}
`);

// the page colour as plain hex, for the browser's bar (<meta name="theme-color">, which can't read CSS variables)
writeFileSync(new URL("../src/app/theme.json", import.meta.url), JSON.stringify({
  seed: SEED,
  page: { light: hexFromArgb(C.surfaceContainerLow.getArgb(schemeOf(false))), dark: hexFromArgb(C.surfaceContainerLow.getArgb(schemeOf(true))) },
}, null, 2) + "\n");
